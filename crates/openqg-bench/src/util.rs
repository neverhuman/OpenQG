use anyhow::{Context, Result};
use serde::de::DeserializeOwned;
use serde::Serialize;
use std::fs;
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

pub fn generated_at() -> String {
    let now = match SystemTime::now().duration_since(UNIX_EPOCH) {
        Ok(now) => now,
        Err(_) => return String::from("0"),
    };
    format!("{}", now.as_secs())
}

pub fn read_jsonl<T: DeserializeOwned>(path: &Path) -> Result<Vec<T>> {
    let text = fs::read_to_string(path).with_context(|| format!("read {}", path.display()))?;
    let mut records = Vec::new();
    for (index, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let record = serde_json::from_str::<T>(line)
            .with_context(|| format!("parse {} line {}", path.display(), index + 1))?;
        records.push(record);
    }
    Ok(records)
}

pub fn write_json<T: Serialize>(path: &Path, value: &T) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, serde_json::to_vec_pretty(value)?)?;
    Ok(())
}

pub fn generated_header(tool: &str, command: &str) -> String {
    format!("Generated by: {tool}\nRegeneration command: {command}\nDO NOT EDIT BY HAND\n\n")
}

pub fn generated_json_text<T: Serialize>(tool: &str, command: &str, value: &T) -> Result<String> {
    Ok(format!(
        "{}{}",
        generated_header(tool, command),
        serde_json::to_string_pretty(value)?,
    ))
}

pub fn write_generated_text(path: &Path, tool: &str, command: &str, body: &str) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, format!("{}{}", generated_header(tool, command), body))?;
    Ok(())
}

pub fn write_generated_json<T: Serialize>(
    path: &Path,
    tool: &str,
    command: &str,
    value: &T,
) -> Result<()> {
    write_generated_text(path, tool, command, &serde_json::to_string_pretty(value)?)
}

pub fn read_generated_json<T: DeserializeOwned>(path: &Path) -> Result<T> {
    let text = fs::read_to_string(path).with_context(|| format!("read {}", path.display()))?;
    let body = match text.starts_with("Generated by:") {
        true => match text.split_once("\n\n") {
            Some((_, body)) => body,
            None => text.as_str(),
        },
        false => text.as_str(),
    };
    serde_json::from_str(body).with_context(|| format!("parse {}", path.display()))
}

pub fn sha256_digest(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    let digest = Sha256::digest(bytes);
    format!("{digest:x}")
}
