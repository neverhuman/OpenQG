//! Theorem catalog: maps the registered certificate relations to their action generators.
//!
//! Each entry proves (in the theorem-statement field) which action term generates the relation,
//! under what assumptions, and at what limit. Normal CI verifies that every relation in
//! `openqg-core::certificate::registered_relations()` appears here.
//!
//! The symbolic derivations are pre-committed formula catalog entries; live CAS (SymPy) runs
//! in a controlled release job and updates `formula_catalog_version` + `action_fingerprint` only.

use serde::{Deserialize, Serialize};

/// What kind of action term generates a relation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum ActionTermKind {
    /// Generated by a normal-DGP brane extension (BraneTerm::NormalDgp).
    NormalDgpBrane {
        /// Which quantity the relation computes (e.g. "beta_function", "geff_over_g").
        computes: String,
        /// Physical limit or regime in which the relation holds.
        limit: String,
    },
    /// Generated by a Hu-Sawicki f(R) term (ScalarTensorTerm::HuSawickiFR).
    HuSawickiFR { computes: String, limit: String },
    /// Generated by a general Horndeski G4 scalar-tensor coupling.
    HorndeskiG4 { computes: String, limit: String },
    /// Generated by a conformal/disformal dark-matter coupling (MatterCoupling::Conformal).
    ConformedDarkMatterCoupling { computes: String, limit: String },
    /// Generated by dark-scattering momentum exchange (MatterCoupling::DarkScatteringDrag).
    DarkScatteringDrag { computes: String, limit: String },
    /// Background / FLRW constraint theorem (no MG mechanism; zero rigor credit).
    BackgroundConstraint { constraint: String },
    /// Phenomenology compatibility map only: no inverse-witness action.
    /// Earns no derivation-rigor credit and cannot satisfy StructurallyGenerated.
    PhenomenologyOnly { note: String },
}

impl ActionTermKind {
    /// True when this entry carries real mechanism content (not a unit theorem or phenomonly).
    pub fn is_mechanism(&self) -> bool {
        !matches!(
            self,
            ActionTermKind::BackgroundConstraint { .. } | ActionTermKind::PhenomenologyOnly { .. }
        )
    }
}

/// One entry in the static theorem catalog.
///
/// Each entry connects a certificate-registry relation name to its algebraic generator,
/// records the theorem statement, physical assumptions, and literature references.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TheoremEntry {
    /// Name matching `certificate::registered_relations()`.
    pub relation: String,
    /// The action term that generates this relation.
    pub action_term: ActionTermKind,
    /// Human-readable theorem statement (what the compiler proves about this relation).
    pub theorem_statement: String,
    /// Physical assumptions under which the theorem holds.
    pub assumptions: Vec<String>,
    /// Literature references (author-year format).
    pub references: Vec<String>,
}

impl TheoremEntry {
    /// True when this entry is generated by a real mechanism (not phenomonly or background).
    pub fn is_mechanism(&self) -> bool {
        self.action_term.is_mechanism()
    }
}

