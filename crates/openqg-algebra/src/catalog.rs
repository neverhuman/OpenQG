/// Look up the theorem entry for a given relation name.
pub fn relation_theorem(relation: &str) -> Option<TheoremEntry> {
    theorem_catalog()
        .into_iter()
        .find(|e| e.relation == relation)
}

/// True when a relation has an action-level mechanism generator (not background/phenomonly).
pub fn relation_is_mechanism(relation: &str) -> bool {
    relation_theorem(relation).is_some_and(|e| e.is_mechanism())
}

/// Return the action term kind for a relation, or `None` if not in the catalog.
pub fn relation_action_term(relation: &str) -> Option<ActionTermKind> {
    relation_theorem(relation).map(|e| e.action_term)
}
